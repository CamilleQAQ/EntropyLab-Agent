from __future__ import annotations

import numpy as np
import pytest

from entropy_agent.classifiers.obt_artifact import (
    load_obt_artifact,
    save_obt_artifact,
)
from entropy_agent.classifiers.obt_lstsvm import (
    OBTLSTSVM,
    class_distance_matrices,
    optimized_class_order,
)
from entropy_agent.classifiers.torch_bt_lstsvm import (
    MatlabCompatTorchBinaryLSTSVM,
)


TRAIN_X = np.array(
    [
        [-3.2, -2.8], [-2.7, -3.1], [-3.1, -3.4], [-2.5, -2.6],
        [2.7, 3.1], [3.2, 2.8], [3.4, 3.3], [2.6, 2.5],
        [-2.4, 2.5], [-1.8, 2.9], [-2.7, 3.2], [-2.1, 3.5],
        [1.0, -1.1], [1.7, -0.6], [0.8, -1.8], [1.9, -1.5],
    ],
    dtype=np.float64,
)
TRAIN_Y = np.repeat(np.array([1, 2, 4, 3]), 4)
TEST_X = np.array(
    [[-3, -3], [3, 3], [-2.2, 3], [1.3, -1.2], [0, 0], [2.1, 1.8]],
    dtype=np.float64,
)

# Frozen values generated by the original MATLAB functions and stored in the
# supplied matlab_reference.mat.  Keeping the constants here makes the project
# tests self-contained without depending on the user's external directory.
MATLAB_INTRA = np.array(
    [0.6596498186926424, 0.7100150258840445, 1.0225431944400587, 0.8028403835201052]
)
MATLAB_INTER = np.array(
    [
        [0, 8.374073876615682, 5.009368790319732, 6.75466811517954],
        [8.374073876615682, 0, 4.616347138917671, 5.618817833367944],
        [5.009368790319732, 4.616347138917671, 0, 5.715402644146226],
        [6.75466811517954, 5.618817833367944, 5.715402644146226, 0],
    ]
)


def test_matches_frozen_matlab_order_distances_and_predictions() -> None:
    model = OBTLSTSVM(kernel_parameter=1.5).fit(TRAIN_X, TRAIN_Y)
    np.testing.assert_array_equal(model.class_order_, [1, 2, 4, 3])
    np.testing.assert_allclose(model.intra_class_distances_, MATLAB_INTRA, rtol=1e-13)
    np.testing.assert_allclose(model.inter_class_distances_, MATLAB_INTER, rtol=1e-13)
    np.testing.assert_array_equal(model.predict(TEST_X), [1, 2, 4, 3, 1, 2])


def test_order_is_training_only_and_prediction_cannot_mutate_it() -> None:
    expected, *_ = optimized_class_order(TRAIN_X, TRAIN_Y)
    model = OBTLSTSVM(kernel="linear").fit(TRAIN_X, TRAIN_Y)
    before = model.class_order_.copy()
    model.predict(np.full((20, 2), 1e9))
    np.testing.assert_array_equal(before, expected)
    np.testing.assert_array_equal(model.class_order_, expected)


def test_matlab_compat_binary_is_the_existing_lsts_twin_definition() -> None:
    positive = TRAIN_X[TRAIN_Y == 1]
    negative = TRAIN_X[TRAIN_Y != 1]
    integrated = OBTLSTSVM(kernel_parameter=1.5).fit(TRAIN_X, TRAIN_Y).nodes_[0]
    existing = MatlabCompatTorchBinaryLSTSVM(
        c1=1.0, c2=1.0, bandwidth=1.5, epsilon=1e-4
    ).fit(
        np.vstack((positive, negative)),
        np.r_[np.ones(len(positive)), -np.ones(len(negative))],
    )
    positive_distance, negative_distance = integrated.decision_distances(TEST_X)
    existing_scores = existing.scores(TEST_X)
    np.testing.assert_allclose(
        positive_distance, existing_scores.positive_distance, rtol=2e-5, atol=2e-5
    )
    np.testing.assert_allclose(
        negative_distance, existing_scores.negative_distance, rtol=2e-5, atol=2e-5
    )
    np.testing.assert_array_equal(integrated.predict(TEST_X), existing.predict(TEST_X))


@pytest.mark.parametrize("kernel", ["linear", "rbf"])
def test_safe_numeric_artifact_round_trip(kernel: str, tmp_path) -> None:
    model = OBTLSTSVM(kernel=kernel, kernel_parameter=1.5).fit(TRAIN_X, TRAIN_Y)
    path = tmp_path / f"obt-{kernel}.npz"
    manifest = save_obt_artifact(path, model, metadata={"source": "unit-test"})
    restored, restored_manifest = load_obt_artifact(path)
    assert restored_manifest == manifest
    assert manifest["algorithm"] == "OBT-LSTSVM"
    np.testing.assert_array_equal(restored.class_order_, model.class_order_)
    np.testing.assert_array_equal(restored.predict(TEST_X), model.predict(TEST_X))


def test_feature_only_mode_removes_historical_label_distance() -> None:
    _, historical, _ = class_distance_matrices(TRAIN_X, TRAIN_Y, matlab_compat=True)
    _, feature_only, _ = class_distance_matrices(TRAIN_X, TRAIN_Y, matlab_compat=False)
    assert np.all(historical[np.triu_indices(4, 1)] > feature_only[np.triu_indices(4, 1)])


def test_float_labels_are_rejected_before_tree_construction() -> None:
    with pytest.raises(ValueError, match="integers"):
        OBTLSTSVM().fit(TRAIN_X, TRAIN_Y.astype(np.float64))
